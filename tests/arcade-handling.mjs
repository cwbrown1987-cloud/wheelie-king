import assert from 'node:assert/strict';
import {createArcadeHandling,classifyRide,HANDLING_PRESETS} from '../ride-arcade-handling.js';
const terrain={height:()=>0};
const bike={comH:.9};
const ground={x:0,y:.9,z:0,vx:10,vy:0,ground:[true,true]};
const air={...ground,y:6,vy:1,ground:[false,false]};
assert.equal(classifyRide(ground,{},terrain,bike),'GROUND');
assert.equal(classifyRide({...ground,ground:[true,false]}, {},terrain,bike),'WHEELIE');
assert.equal(classifyRide({...ground,ground:[false,true]}, {},terrain,bike),'STOPPIE');
assert.equal(classifyRide({...ground,drift:true}, {},terrain,bike),'DRIFT');
assert.equal(classifyRide(air,{},terrain,bike),'AIR');
assert.equal(classifyRide({...air,y:2,vy:-2}, {},terrain,bike),'LANDING');
assert.equal(classifyRide({...air,crashed:'FELL OVER'}, {},terrain,bike),'CRASH');
const handling=createArcadeHandling();
const input={steer:1,lean:1,throttle:.5};
assert.strictEqual(handling.prepareInput(ground,input,1/60,terrain,bike),input,'original passthrough');
assert(handling.setMode('balanced'));
const shaped=handling.prepareInput(ground,input,1/60,terrain,bike);
assert.notStrictEqual(shaped,input);
assert.equal(shaped.lean,input.lean);
assert.equal(shaped.throttle,input.throttle);
assert(shaped.arcade.steeringRate>4);
assert(shaped.arcade.lateralG>.9);
assert.equal(handling.snapshot().state,'GROUND');
handling.prepareInput(air,input,1/60,terrain,bike);
assert.equal(handling.snapshot().assistance.trickIntent,true);
assert.equal(handling.snapshot().assistance.airRollFactor,.2);
handling.setSetting('landing',.8);
assert.equal(handling.getMode(),'custom');
assert.equal(handling.getSettings().landing,.8);
assert.equal(handling.setMode('not-a-mode'),false);
handling.setMode('arcade');
assert(handling.getSettings().grip>HANDLING_PRESETS.balanced.grip);
handling.setMode('original');
assert.strictEqual(handling.prepareInput(ground,input,1/60,terrain,bike),input);
const reset=createArcadeHandling({mode:'arcade'});
reset.prepareInput({...air,y:2,vy:-2},{steer:0,lean:0},1/60,terrain,bike);
assert.equal(reset.snapshot().state,'LANDING');
assert(reset.snapshot().assistance.airRollFactor>1);
console.log('Arcade handling: state detection, original fallback, tuning, trick suppression PASS');
